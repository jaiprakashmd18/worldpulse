// Builds the public runtime config (js/config.js) from environment variables.
import { readFileSync, existsSync } from 'node:fs';

/** Loads KEY=value pairs from .env (if present) without overriding real env vars. */
export function loadDotEnv(file = new URL('../.env', import.meta.url)) {
  if (!existsSync(file)) return;
  for (const line of readFileSync(file, 'utf8').split(/\r?\n/)) {
    const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*?)\s*$/);
    if (!m || line.trim().startsWith('#')) continue;
    const value = m[2].replace(/^(['"])(.*)\1$/, '$2');
    if (!(m[1] in process.env)) process.env[m[1]] = value;
  }
}

export function configSource(env = process.env) {
  const url = (env.WORLDPULSE_SUPABASE_URL || env.SUPABASE_URL || '').trim();
  const key = (env.WORLDPULSE_SUPABASE_ANON_KEY || env.SUPABASE_ANON_KEY || '').trim();
  if (url && !/^https:\/\/[a-z0-9.-]+$/i.test(url.replace(/\/$/, ''))) {
    throw new Error(`WORLDPULSE_SUPABASE_URL must look like https://<project>.supabase.co (got "${url}")`);
  }
  if (key && looksLikeServiceRole(key)) {
    throw new Error('Refusing to publish a service-role key. Use the anon / publishable key for WORLDPULSE_SUPABASE_ANON_KEY.');
  }
  const config = {
    supabaseUrl: url.replace(/\/$/, ''),
    supabaseAnonKey: key,
    pollIntervalMs: Number(env.WORLDPULSE_POLL_INTERVAL_MS) || 60000,
    contactEmail: (env.WORLDPULSE_CONTACT_EMAIL || '').trim(),
    githubUrl: (env.WORLDPULSE_GITHUB_URL || '').trim(),
    siteUrl: (env.WORLDPULSE_SITE_URL || 'https://ghost-gobal.vercel.app').trim(),
  };
  return `// Generated by scripts/build.mjs — public values only.\nwindow.WORLDPULSE_CONFIG = ${JSON.stringify(config, null, 2)};\n`;
}

function looksLikeServiceRole(key) {
  if (key.startsWith('sb_secret_')) return true;
  const payload = key.split('.')[1];
  if (!payload) return false;
  try {
    return JSON.parse(Buffer.from(payload, 'base64url').toString()).role === 'service_role';
  } catch {
    return false;
  }
}
