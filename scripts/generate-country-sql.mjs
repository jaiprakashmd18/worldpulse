// Regenerates supabase/seed_countries.sql from js/countries.js so the
// server-side list of valid country codes matches the frontend exactly.
// Usage: node scripts/generate-country-sql.mjs
import { writeFileSync } from 'node:fs';
import { COUNTRIES } from '../js/countries.js';

const esc = (s) => s.replace(/'/g, "''");
const rows = COUNTRIES.map((c) => `  ('${c.code}', '${esc(c.name)}')`).join(',\n');
const sql = `-- Generated by scripts/generate-country-sql.mjs — do not edit by hand.
insert into private.countries (code, name) values
${rows}
on conflict (code) do update set name = excluded.name;
`;
writeFileSync(new URL('../supabase/seed_countries.sql', import.meta.url), sql);
console.log(`Wrote ${COUNTRIES.length} countries to supabase/seed_countries.sql`);
